/** Helper to generate mock individual votes for a Senate proposition. */
export function generateMockVotes(
  yesCount: number,
  noCount: number,
  abstCount: number,
  absentCount: number,
): PropositionVote[] {
  const parties = ["PL", "MDB", "PT", "PSD", "UNIÃO", "PP", "PODE", "PDT", "PSDB", "PSB", "REPUBLICANOS", "NOVO"]
  const ufs = ["SP", "MG", "RJ", "BA", "RS", "PR", "CE", "PE", "GO", "PA", "MA", "SC", "AM", "MT", "MS", "DF", "RO"]
  const firstNames = ["Flávio", "Renan", "Simone", "Randolfe", "Eduardo", "Rogério", "Eliziane", "Omar", "Humberto", "Jorge", "Marcos", "Tereza", "Veneziano", "Jaques", "Davi", "Ciro"]
  const lastNames = ["Bolsonaro", "Calheiros", "Tebet", "Rodrigues", "Braga", "Marinho", "Gama", "Aziz", "Costa", "Kajuru", "Pontes", "Cristina", "Vital", "Wagner", "Alcolumbre", "Nogueira"]

  const votes: PropositionVote[] = []
  let id = 1

  const addVotes = (count: number, voteType: PropositionVote["vote"]) => {
    for (let i = 0; i < count; i++) {
      votes.push({
        parliamentarianId: String(id++),
        parliamentarianName: `${firstNames[i % firstNames.length]} ${lastNames[(i + 2) % lastNames.length]}`,
        party: parties[i % parties.length],
        uf: ufs[i % ufs.length],
        vote: voteType,
      })
    }
  }

  addVotes(yesCount, "Sim")
  addVotes(noCount, "Não")
  addVotes(abstCount, "Abstenção")
  addVotes(absentCount, "Ausente")

  return votes
}

